create or replace dynamic table ZERO_TO_ONE_CHAIN.L2_STAGE.STG_SUPPLIER_PERFORMANCE(
	RECORD_ID,
	SUPPLIER_ID,
	EVALUATION_DATE,
	PERIOD_START,
	PERIOD_END,
	REVIEW_TYPE,
	TOTAL_POS_IN_PERIOD,
	ON_TIME_DELIVERIES,
	OTD_PCT,
	IN_FULL_DELIVERIES,
	OTIF_PCT,
	QUALITY_INCIDENTS,
	DEFECT_PPM,
	QUALITY_SCORE,
	RESPONSIVENESS_SCORE,
	COST_SCORE,
	INNOVATION_SCORE,
	SUSTAINABILITY_SCORE,
	COMPOSITE_SCORE,
	GRADE,
	NCR_COUNT,
	CORRECTIVE_ACTIONS_OPEN,
	CORRECTIVE_ACTIONS_CLOSED,
	AVG_LEAD_TIME_DAYS,
	LEAD_TIME_VARIANCE_DAYS,
	RECOMMENDATION,
	_LOADED_AT,
	_SOURCE_SYSTEM,
	_STAGED_AT
) target_lag = '1 hour' refresh_mode = AUTO initialize = ON_CREATE warehouse = Z21_WH
 as
SELECT
    record_id,
    UPPER(TRIM(supplier_id)) AS supplier_id,
    evaluation_date::DATE AS evaluation_date,
    period_start::DATE AS period_start,
    period_end::DATE AS period_end,
    UPPER(TRIM(review_type)) AS review_type,
    total_pos_in_period,
    on_time_deliveries,
    ROUND(DIV0(on_time_deliveries, total_pos_in_period) * 100, 2) AS otd_pct,
    in_full_deliveries,
    ROUND(DIV0(in_full_deliveries, total_pos_in_period) * 100, 2) AS otif_pct,
    quality_incidents,
    defect_ppm,
    quality_score,
    responsiveness_score,
    cost_score,
    innovation_score,
    sustainability_score,
    ROUND(quality_score * 0.3 + responsiveness_score * 0.2 + cost_score * 0.2 + DIV0(on_time_deliveries, GREATEST(total_pos_in_period, 1)) * 10 * 0.2 + innovation_score * 0.1, 2) AS composite_score,
    CASE
        WHEN composite_score >= 8 THEN 'A'
        WHEN composite_score >= 6 THEN 'B'
        WHEN composite_score >= 4 THEN 'C'
        ELSE 'D'
    END AS grade,
    ncr_count,
    corrective_actions_open,
    corrective_actions_closed,
    avg_lead_time_days,
    lead_time_variance_days,
    UPPER(TRIM(recommendation)) AS recommendation,
    _loaded_at,
    _source_system,
    CURRENT_TIMESTAMP() AS _staged_at
FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_SRM_SUPPLIER_PERFORMANCE;
