create or replace alert ZERO_TO_ONE_CHAIN.L8_ACTION.ALERT_DQ_CRITICAL
	warehouse=Z21_WH
	schedule='USING CRON 0 * * * * UTC'
	if (exists(
		SELECT 1
        FROM ZERO_TO_ONE_CHAIN.L3_VALIDATE.DQ_QUARANTINE
        WHERE severity = 'CRITICAL' AND resolved_at IS NULL
        HAVING COUNT(*) > 50
	))
	then
	INSERT INTO ZERO_TO_ONE_CHAIN.L8_ACTION.RECOMMENDATIONS
            (category, severity, title, description, recommended_action, status)
        VALUES ('QUALITY', 'CRITICAL',
                'DQ circuit breaker: >50 critical issues in quarantine',
                'Data quality quarantine has accumulated critical issues. Pipeline may be halted.',
                'Review quarantine table, resolve critical issues, then re-run circuit breaker.',
                'PENDING');

create or replace alert ZERO_TO_ONE_CHAIN.L8_ACTION.ALERT_OTD_SLA_BREACH
	warehouse=Z21_WH
	schedule='USING CRON 0 */6 * * * UTC'
	if (exists(
		SELECT 1
        FROM ZERO_TO_ONE_CHAIN.L6_SEMANTIC.VW_METRIC_OTD
        WHERE ORDER_DATE >= DATEADD(DAY, -7, CURRENT_DATE())
        HAVING AVG(CASE WHEN IS_ON_TIME THEN 1 ELSE 0 END) * 100 < 85
	))
	then
	INSERT INTO ZERO_TO_ONE_CHAIN.L8_ACTION.RECOMMENDATIONS
            (category, severity, title, description, recommended_action, status)
        VALUES ('DELIVERY', 'CRITICAL',
                'OTD below 85% SLA in last 7 days',
                'On-Time Delivery has dropped below the 85% SLA threshold. Immediate action required.',
                'Review late orders, identify root causes, expedite pending shipments.',
                'PENDING');

create or replace alert ZERO_TO_ONE_CHAIN.L8_ACTION.ALERT_STOCKOUT
	warehouse=Z21_WH
	schedule='USING CRON 0 */4 * * * UTC'
	if (exists(
		SELECT 1
