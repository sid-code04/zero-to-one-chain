create or replace view ZERO_TO_ONE_CHAIN.L8_ACTION.VW_PIPELINE_HEALTH(
	TASK_NAME,
	STATE,
	SCHEDULED_TIME,
	COMPLETED_TIME,
	DURATION_SECONDS,
	ERROR_CODE,
	ERROR_MESSAGE,
	RETURN_VALUE
) as
SELECT
    name AS task_name,
    state,
    scheduled_time,
    completed_time,
    DATEDIFF(SECOND, scheduled_time, completed_time) AS duration_seconds,
    error_code,
    error_message,
    return_value
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
    SCHEDULED_TIME_RANGE_START => DATEADD(DAY, -7, CURRENT_TIMESTAMP()),
    RESULT_LIMIT => 100
))
WHERE DATABASE_NAME = 'ZERO_TO_ONE_CHAIN'
ORDER BY scheduled_time DESC;

CREATE OR REPLACE PROCEDURE ZERO_TO_ONE_CHAIN.L8_ACTION.SP_PROMOTE_DEV_TO_UAT()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN
    -- Gate: check DQ quarantine in DEV
    LET critical_count NUMBER := (SELECT COUNT(*) FROM ZERO_TO_ONE_CHAIN.L3_VALIDATE.DQ_QUARANTINE WHERE severity = ''CRITICAL'' AND resolved_at IS NULL);

    IF (:critical_count > 0) THEN
        INSERT INTO ZERO_TO_ONE_CHAIN.L8_ACTION.ENVIRONMENT_REGISTRY
            (source_env, target_env, promoted_by, circuit_breaker_result, status, notes)
        VALUES (''DEV'', ''UAT'', CURRENT_USER(), ''BLOCKED: '' || :critical_count || '' critical issues'',
                ''BLOCKED'', ''Promotion blocked — resolve critical DQ issues first'');
        RETURN ''BLOCKED: '' || :critical_count || '' critical DQ issues in DEV. Resolve before promoting.'';
    END IF;

    -- Refresh UAT L1 raw data from DEV
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_ERP_PURCHASE_ORDERS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_ERP_PURCHASE_ORDERS;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_ERP_SALES_ORDERS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_ERP_SALES_ORDERS;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_ERP_INVENTORY_SNAPSHOTS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_ERP_INVENTORY_SNAPSHOTS;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_TMS_SHIPMENTS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_TMS_SHIPMENTS;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_SRM_SUPPLIER_PERFORMANCE AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_SRM_SUPPLIER_PERFORMANCE;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_IOT_SENSOR_READINGS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_IOT_SENSOR_READINGS;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_ERP_VENDORS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_ERP_VENDORS;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_SRM_SUPPLIERS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_SRM_SUPPLIERS;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_ERP_MATERIALS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_ERP_MATERIALS;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_ERP_PLANTS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_ERP_PLANTS;
    CREATE OR REPLACE TABLE ZERO_TO_ONE_CHAIN_UAT.L1_INGESTION.RAW_ERP_CUSTOMERS AS SELECT * FROM ZERO_TO_ONE_CHAIN.L1_INGESTION.RAW_ERP_CUSTOMERS;

    -- Grant roles
    GRANT USAGE ON DATABASE ZERO_TO_ONE_CHAIN_UAT TO ROLE Z21_ADMIN;
    GRANT USAGE ON DATABASE ZERO_TO_ONE_CHAIN_UAT TO ROLE Z21_PLANNER;
    GRANT USAGE ON DATABASE ZERO_TO_ONE_CHAIN_UAT TO ROLE Z21_PROCUREMENT;
    GRANT USAGE ON DATABASE ZERO_TO_ONE_CHAIN_UAT TO ROLE Z21_LOGISTICS;

    -- Log
    INSERT INTO ZERO_TO_ONE_CHAIN.L8_ACTION.ENVIRONMENT_REGISTRY
        (source_env, target_env, promoted_by, circuit_breaker_result, dbt_test_result, status, notes)
    VALUES (''DEV'', ''UAT'', CURRENT_USER(), ''PASSED: 0 critical'', ''PENDING — run dbt test --target uat'',
            ''SUCCESS'', ''L1 data promoted. Run dbt run + test against UAT to complete.'');

    RETURN ''SUCCESS: DEV data promoted to UAT. Now run dbt --target uat to build transformations.'';
END';

CREATE OR REPLACE PROCEDURE ZERO_TO_ONE_CHAIN.L8_ACTION.SP_PROMOTE_UAT_TO_PROD()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS 'BEGIN
    -- Gate 1: check UAT has tables
    LET table_count NUMBER := (SELECT COUNT(*) FROM ZERO_TO_ONE_CHAIN_UAT.INFORMATION_SCHEMA.TABLES WHERE TABLE_SCHEMA = ''L1_INGESTION'');
    IF (:table_count = 0) THEN
        RETURN ''BLOCKED: UAT has no L1 tables. Promote DEV to UAT first.'';
    END IF;

    -- Gate 2: check UAT DQ (quarantine table may not exist in UAT yet, so check DEV)
    LET critical_count NUMBER := (SELECT COUNT(*) FROM ZERO_TO_ONE_CHAIN.L3_VALIDATE.DQ_QUARANTINE WHERE severity = ''CRITICAL'' AND resolved_at IS NULL);
    IF (:critical_count > 0) THEN
